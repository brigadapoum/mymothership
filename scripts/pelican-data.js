/** Прямоугольник плана → координаты сцены (картинка плана растянута на sceneRect). */
export function toScene([x, y, w, h], rect) {
  const k = rect.width / PLAN.w;
  const m = rect.height / PLAN.h;
  return { x: rect.x + x * k, y: rect.y + y * m, width: w * k, height: h * m };
}
