def uid(*parts):
    """Стабильный 16-символьный id: пересборка не плодит дубликаты в мире."""
    h = hashlib.sha256("|".join(parts).encode()).digest()
    abc = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"
    return "".join(abc[b % len(abc)] for b in h[:16])


