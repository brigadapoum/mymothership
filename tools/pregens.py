def html_section(title, rows):
    out = f"<h3>{title}</h3>" if title else ""
    for r in rows:
        if isinstance(r, tuple):
            out += f"<p><strong>{r[0]}:</strong> {r[1]}</p>"
        else:
            out += f"<p>{r}</p>"
    return out


