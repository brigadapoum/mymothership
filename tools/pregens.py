def years(n):
    if n % 10 == 1 and n % 100 != 11:
        return f"{n} год"
    if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14):
        return f"{n} года"
    return f"{n} лет"


def biography(c):
    head = f"<p><em>{c['job']}{', ' + years(c['age']) if c['age'] else ''}. {c['tagline']}</em></p>"
    rows = [("Вид", c["look"]), ("Манера", c["manner"]), ("Чем думает", c["thinks"]),
            ("Желание", c["wants"]), ("Польза", c["use"])]
    if c.get("family"):
        rows.append(("Близкие на станции", c["family"]))
    rows.append(("Где в момент удара", c["where"]))
    rows += c.get("extra", [])
    return head + html_section("", rows)


def notes(c):
    out = html_section(c.get("secret_title", "Тайна"), [c["secret"]] + c.get("secret_more", []))
    out += html_section("Как держится", [("Голосует", c["votes"]), ("Где ломается", c["breaks"])])
    if c["ties"]:
        out += html_section("Связи", c["ties"])
    rows = []
    if c.get("if_player"):
        rows.append(("Если играет игрок", c["if_player"]))
    rows.append(("Если NPC", c["if_npc"]))
    out += html_section("Смотрителю", rows)
    return out


